-- CodeCanvas schema v1: student accounts and graded attempts.
-- Kept to portable SQL so it runs on PostgreSQL (prod) and H2 in PostgreSQL mode (tests).

CREATE TABLE students (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username       VARCHAR(30)  NOT NULL,
    display_name   VARCHAR(50)  NOT NULL,
    password_hash  VARCHAR(100) NOT NULL,
    role           VARCHAR(20)  NOT NULL DEFAULT 'STUDENT',
    enabled        BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_students_username UNIQUE (username)
);

-- One row per finished quiz or mock exam. Score is computed by the server, never by the browser.
CREATE TABLE attempts (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id    BIGINT       NOT NULL,
    kind          VARCHAR(10)  NOT NULL,          -- QUIZ or EXAM
    curriculum    VARCHAR(10)  NOT NULL,          -- APCS or ICSE
    topic         VARCHAR(100),                   -- null for mock exams
    score         INT          NOT NULL,
    total         INT          NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_attempts_student FOREIGN KEY (student_id) REFERENCES students (id) ON DELETE CASCADE,
    CONSTRAINT ck_attempts_kind CHECK (kind IN ('QUIZ', 'EXAM')),
    CONSTRAINT ck_attempts_curriculum CHECK (curriculum IN ('APCS', 'ICSE')),
    CONSTRAINT ck_attempts_score CHECK (score >= 0 AND total > 0 AND score <= total)
);

CREATE INDEX ix_attempts_student_kind ON attempts (student_id, kind, created_at);
