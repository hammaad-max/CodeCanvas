-- LoopLab schema v2: student email (for password reset) and one-time password reset tokens.
-- Only adds things, so the previous release keeps working against this schema (safe rollback).

ALTER TABLE students ADD COLUMN email VARCHAR(254);
ALTER TABLE students ADD CONSTRAINT uq_students_email UNIQUE (email);

-- Only a SHA-256 hash of each token is stored; the token itself exists only in the emailed link.
CREATE TABLE password_reset_tokens (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id  BIGINT       NOT NULL REFERENCES students (id) ON DELETE CASCADE,
    token_hash  VARCHAR(64)  NOT NULL,
    expires_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    used_at     TIMESTAMP WITH TIME ZONE,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_password_reset_token_hash UNIQUE (token_hash)
);

CREATE INDEX idx_password_reset_student ON password_reset_tokens (student_id, created_at);
